#!/usr/bin/env python3
"""Regenerate src/port/unresolved_stubs.c from the linker's undefined-symbol list (stdin: build output).
Weak definitions: a function logs the first call and aborts; data is zeroed storage. Real definitions win."""
import re, sys
names = sorted({m.group(1) for l in sys.stdin for m in [re.match(r'\s+"_(\w+)", referenced', l)] if m})
out = ['/* Generated by tools/port/gen_unresolved_stubs.py - placeholders for symbols not yet ported. */\n',
       '#include <stdio.h>\n#include <stdlib.h>\n\n']
for n in names:
    if re.match(r'(g[A-Z]|D_)', n):
        out.append(f'__attribute__((weak)) unsigned char {n}[0x10000];\n')
    else:
        out.append(f'__attribute__((weak)) void {n}(void) {{ fprintf(stderr, "unresolved call: {n}\\n"); abort(); }}\n')
open('src/port/unresolved_stubs.c', 'w').write(''.join(out))
print(len(names))
