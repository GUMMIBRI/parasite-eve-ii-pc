#!/usr/bin/env python3
"""Emit cmake/overlay_variants.cmake: every variant unit (a package compiling another package's shared source)
with the -D parameters its manifest slot declares. Source: configs/USA/generated/*.yaml + overlays.toml."""
import tomllib, pathlib, re, glob
m = tomllib.loads(pathlib.Path("configs/USA/overlays.toml").read_text())
slots = {}
for fam, spec in m.items():
    for e in spec.get("overlays", {}).values():
        for s in e.get("slots") or []:
            d = {k: str(v) for k, v in (s.get("defines") or {}).items()}
            if s.get("aliases"):
                d["PACKAGE_ALIASES"] = "".join(f"DEFINE_ALIAS({a},{b});" for a, b in s["aliases"].items())
            slots[s["package"]] = d
out = ["# Generated by tools/port/gen_overlay_variants.py\n"]
n = 0
for y in sorted(glob.glob("configs/USA/generated/*.yaml")):
    pkg = pathlib.Path(y).stem
    for line in pathlib.Path(y).read_text().splitlines():
        mm = re.search(r"type: variantsrc, name: (\S+), source: ([^}\s]+)", line)
        if not mm:
            continue
        unit, src = mm.group(1).rstrip(","), mm.group(2)
        if not src.startswith("src/"):
            hits = glob.glob(f"src/*/{src}.c")
            if len(hits) != 1:
                print("unresolved", pkg, src, hits); continue
            src = hits[0][:-2]
        d = dict(slots.get(pkg, {}))
        al = d.pop("PACKAGE_ALIASES", "")
        hdr = ""
        if al:
            hdr = f"cmake/aliases/{unit.replace('/', '__')}.h"
            pathlib.Path(hdr).parent.mkdir(exist_ok=True)
            pathlib.Path(hdr).write_text(f"#define PACKAGE_ALIASES {al}\n")
        defs = ";".join(f"{k}={v}" for k, v in sorted(d.items()))
        out.append(f'pe_overlay_variant("{pkg}" "{unit}" "{src}.c" "{defs}" "{hdr}")\n')
        n += 1
pathlib.Path("cmake/overlay_variants.cmake").write_text("".join(out))
print(n, "variant units")
