#!/usr/bin/env python3
"""Write src/port/asset_parts_table.c: the layout table the runtime asset loader uses (no game data).

Usage: gen_asset_table.py parts.json manifest.json > src/port/asset_parts_table.c"""
import json, sys

parts = json.load(open(sys.argv[1]))
man = json.load(open(sys.argv[2]))
pkgs = sorted({p['package'] for p in parts})
index = {n: i for i, n in enumerate(pkgs)}
ops = {'copy': 0, 'rotation': 0, 'grid_table': 1}
cells = {(p['package'], p['source']): p['offset'] for p in parts if p['kind'] == 'collision' and p['part'] == 'cells'}
print('/* Generated by tools/port/gen_asset_table.py; layout facts only. */')
print('#include "port/asset_parts.h"')
print('const PeAssetPackage gPeAssetPackages[] = {')
for n in pkgs:
    if n == 'main.exe':
        print('    { "main.exe", -1, 0, 0 },')
        continue
    m = man['packages'][n]
    print(f'    {{ "{n}", {m["stage"]}, {m.get("disc_folder", 0)}, {m["disc_file"]} }},')
print('};')
print(f'const int gPeAssetPackageCount = {len(pkgs)};')
rows = sorted(parts, key=lambda p: p['file'][:-4].encode())
print('const PeAssetPart gPeAssetParts[] = {')
for p in rows:
    key = p['file'][:-4]
    cell = cells.get((p['package'], p['source']), 0) if p['op'] == 'grid_table' else 0
    print(f'    {{ "{key}", {index[p["package"]]}, {p["offset"]}u, {p["size"]}u, {ops[p["op"]]}, {p["load"]}u, {cell}u }},')
print('};')
print(f'const int gPeAssetPartCount = {len(rows)};')
