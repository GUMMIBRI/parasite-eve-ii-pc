enum { CAP_FONT_MAP_HEADER = 128, CAP_FONT_MAP_CELLS = 1024,
       CAP_FONT_RUN_CODES = 4096, CAP_FONT_MAX_PACKED_BYTES = 16 * 1024 * 1024 };
typedef struct {
    unsigned glyphCount, foreground;
    unsigned char ascii[CAP_FONT_MAP_CELLS];
    PsyzFontRegion region;
    PsyzFontIdentity identity;
    uint64_t glyphHash[2];
} PeCapFontMap;

static unsigned capFontU16(const unsigned char* p)
{
    return p[0] | (unsigned)p[1] << 8;
}
static uint32_t capFontU32(const unsigned char* p)
{
    return p[0] | (uint32_t)p[1] << 8 | (uint32_t)p[2] << 16 | (uint32_t)p[3] << 24;
}
static uint64_t capFontU64(const unsigned char* p)
{
    uint64_t result = 0;
    for (unsigned i = 0; i < 8; ++i) result |= (uint64_t)p[i] << (8 * i);
    return result;
}
static int capFontHashEqual(const uint64_t left[2], const uint64_t right[2])
{
    return left[0] == right[0] && left[1] == right[1];
}
static int capFontGlyphHash(const PeCapFontSource* source, uint64_t result[2])
{
    if (!source->cells || !source->glyphCount || source->glyphCount > CAP_FONT_MAP_CELLS)
        return 0;
    unsigned count = (unsigned)source->glyphCount;
    unsigned char canonical[4 + CAP_FONT_MAP_CELLS * 4];
    for (unsigned i = 0; i < 4; ++i) canonical[i] = (unsigned char)(count >> (8 * i));
    for (unsigned i = 0; i < count; ++i) {
        canonical[4 + i * 4] = source->cells[i].u;
        canonical[5 + i * 4] = source->cells[i].v;
        canonical[6 + i * 4] = source->cells[i].width;
        canonical[7 + i * 4] = source->cells[i].height;
    }
    Psyz_FontHash128(canonical, 4 + (size_t)count * 4, result);
    return 1;
}
static int capFontCellContained(const TextGlyphCell* cell, const PsyzFontRegion* region)
{
    unsigned endU = (unsigned)cell->u + cell->width;
    unsigned endV = (unsigned)cell->v + cell->height;
    /* A corner narrowing to byte zero is a wrapped source polygon. */
    return cell->width && cell->height && endU < 256 && endV < 256 &&
        cell->u >= region->u && cell->v >= region->v &&
        endU <= region->u + region->w && endV <= region->v + region->h;
}

/* Transactional, bounded, read-only external admission. No private map is
 * embedded, inferred from a UV, or generated by the runtime. */
static PeCapFontMap* capFontReadMap(const PeCapAsset* asset)
{
    const char* explicitRoot = getenv("PE2_CAP_FONT_DIR");
    if (explicitRoot && !*explicitRoot) return NULL;
    static const char* const roots[] = {
        "/mnt/usb0/parasite-eve-ii/font-maps", "/mnt/usb1/parasite-eve-ii/font-maps",
        "/mnt/usb2/parasite-eve-ii/font-maps", "/mnt/usb3/parasite-eve-ii/font-maps",
        "/mnt/usb4/parasite-eve-ii/font-maps", "/mnt/usb5/parasite-eve-ii/font-maps",
        "/mnt/usb6/parasite-eve-ii/font-maps", "/mnt/usb7/parasite-eve-ii/font-maps"
    };
    PeCapFontSource source;
    uint64_t packedHash[2], glyphHash[2];
    if (!peCapAssetFontSource(asset, &source) || !source.packed ||
        !source.bytes || source.bytes > CAP_FONT_MAX_PACKED_BYTES ||
        !capFontGlyphHash(&source, glyphHash)) return NULL;
    Psyz_FontHash128(source.packed, source.bytes, packedHash);
    char path[1200];
    FILE* file = NULL;
    unsigned rootCount = explicitRoot ? 1 : (unsigned)(sizeof(roots) / sizeof(roots[0]));
    for (unsigned i = 0; i < rootCount; ++i) {
        const char* root = explicitRoot ? explicitRoot : roots[i];
        int pathBytes = snprintf(path, sizeof(path), "%s/%016llx%016llx.pcapmap", root,
            (unsigned long long)packedHash[1], (unsigned long long)packedHash[0]);
        if (pathBytes < 0 || pathBytes >= (int)sizeof(path)) return NULL;
        errno = 0;
        file = fopen(path, "rb");
        if (file) break;
        if (errno != ENOENT && errno != ENOTDIR) return NULL;
    }
    if (!file) return NULL;
    unsigned char header[CAP_FONT_MAP_HEADER];
    PeCapFontMap staged = {0};
    if (fread(header, 1, sizeof(header), file) != sizeof(header)) goto reject;
    if (memcmp(header, "PCAPMAP1", 8) || capFontU16(header + 8) != CAP_FONT_MAP_HEADER ||
        capFontU16(header + 10) != 1 || capFontU16(header + 12) != 4 ||
        capFontU16(header + 14) != 0 || capFontU64(header + 16) != source.bytes ||
        capFontU64(header + 24) != packedHash[0] || capFontU64(header + 32) != packedHash[1] ||
        capFontU32(header + 40) != source.glyphCount ||
        capFontU64(header + 48) != glyphHash[0] || capFontU64(header + 56) != glyphHash[1])
        goto reject;
    for (unsigned i = 113; i < CAP_FONT_MAP_HEADER; ++i) if (header[i]) goto reject;
    unsigned entries = capFontU32(header + 44);
    if (!entries || entries > source.glyphCount || entries > CAP_FONT_MAP_CELLS) goto reject;
    staged.glyphCount = (unsigned)source.glyphCount;
    staged.glyphHash[0] = glyphHash[0];
    staged.glyphHash[1] = glyphHash[1];
    staged.region.page = capFontU32(header + 64);
    staged.region.clut = capFontU32(header + 68);
    staged.region.u = capFontU16(header + 72);
    staged.region.v = capFontU16(header + 74);
    staged.region.w = capFontU16(header + 76);
    staged.region.h = capFontU16(header + 78);
    staged.identity.texture[0] = capFontU64(header + 80);
    staged.identity.texture[1] = capFontU64(header + 88);
    staged.identity.palette[0] = capFontU64(header + 96);
    staged.identity.palette[1] = capFontU64(header + 104);
    staged.foreground = header[112];
    /* Version 1 admits P4, blend-neutral page metadata and the original plain
     * text palette only. Other palettes/choice highlighting remain original. */
    if (staged.region.page > 31 || staged.region.clut != 0x3D50 ||
        !staged.region.w || !staged.region.h || staged.region.u >= 256 || staged.region.v >= 256 ||
        staged.region.w > 256 - staged.region.u || staged.region.h > 256 - staged.region.v ||
        staged.foreground > 15) goto reject;
    unsigned previous = 0;
    for (unsigned i = 0; i < entries; ++i) {
        unsigned char record[4];
        if (fread(record, 1, sizeof(record), file) != sizeof(record)) goto reject;
        unsigned cell = capFontU16(record);
        if (cell >= staged.glyphCount || (i && cell <= previous) ||
            record[2] < 32 || record[2] > 126 || record[3] ||
            !capFontCellContained(&source.cells[cell], &staged.region)) goto reject;
        previous = cell;
        staged.ascii[cell] = record[2];
    }
    if (fgetc(file) != EOF || (ferror)(file)) goto reject;
    if (fclose(file)) return NULL;
    PeCapFontMap* map = malloc(sizeof(*map));
    if (map) *map = staged;
    return map;
reject:
    fclose(file);
    return NULL;
}

static int capFontPreflight(const PeCapAsset* asset, const PeCapFontMap* map,
                           const TextGlyphCell* cells, const u16* text,
                           unsigned page, unsigned clut, PsyzFontToken* token, uint64_t* metricKey)
{
    if (!map || !text || page != map->region.page || clut != map->region.clut) return 0;
    PeCapFontSource source;
    uint64_t glyphHash[2];
    if (!peCapAssetFontSource(asset, &source) || source.cells != cells ||
        source.glyphCount != map->glyphCount || !capFontGlyphHash(&source, glyphHash) ||
        !capFontHashEqual(glyphHash, map->glyphHash)) return 0;
    uintptr_t begin = (uintptr_t)source.textBegin, end = (uintptr_t)source.textEnd;
    uintptr_t address = (uintptr_t)text;
    if ((address & 1) || address < begin || address >= end) return 0;
    size_t words = (end - address) / 2;
    if (words > CAP_FONT_RUN_CODES) words = CAP_FONT_RUN_CODES;
    unsigned glyphs = 0;
    int terminated = 0;
    for (size_t i = 0; i < words; ++i) {
        unsigned code = text[i];
        if (code == 0xFFFF) { terminated = 1; break; }
        if (code == 0xFFFE || code == 0xFFFD) continue;
        if ((code & 0x8000) || (code & 0x0C00)) return 0;
        unsigned cell = code & 0x3FF;
        if (cell >= map->glyphCount || !map->ascii[cell] ||
            !capFontCellContained(&cells[cell], &map->region)) return 0;
        ++glyphs;
    }
    if (!terminated || !glyphs) return 0;
    PsyzFontIdentity live;
    uint16_t foreground;
    if (!Psyz_FontIdentityAcquire(&map->region, &live, token) ||
        !capFontHashEqual(live.texture, map->identity.texture) ||
        !capFontHashEqual(live.palette, map->identity.palette) ||
        !Psyz_FontIdentityForeground(token, map->foreground, &foreground) || !foreground ||
        !Psyz_FontIdentityValidate(token)) return 0;
    *metricKey=0;
    if(Psyz_GpuGetFontStyle(PSYZ_FONT_DIALOGUE)>=PSYZ_FONT_RETRO){
        PsyzCapFontMetric *metrics=calloc(map->glyphCount,sizeof(*metrics));
        if(!metrics)return 0;unsigned count=0;
        for(unsigned i=0;i<map->glyphCount;++i)if(map->ascii[i]){
            const TextGlyphCell *g=&cells[i];
            metrics[count++]=(PsyzCapFontMetric){i,map->ascii[i],g->u,g->v,g->width,g->height,g->height,g->width-1};
        }
        *metricKey=Psyz_GpuPreparePlexCapMetrics(metrics,count,map->foreground,token);free(metrics);
        if(!*metricKey)return 0;
        for(size_t i=0;i<words;++i){unsigned code=text[i];if(code==0xffff)break;
            if(code==0xfffe||code==0xfffd)continue;
            if(!Psyz_GpuPlexCapMetricSupports(*metricKey,code&0x3ff)){*metricKey=0;return 0;}
        }
        return Psyz_GpuPreparePlexCapMetricRun(*metricKey,glyphs);
    }
    if(!Psyz_GpuPreparePlexCapRun(glyphs))return 0;
    return 1;
}
